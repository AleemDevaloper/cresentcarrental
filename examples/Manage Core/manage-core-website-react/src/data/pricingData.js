export function serviceTierPricing(service) {
  const prices =
    SERVICE_PRICE_OVERRIDES[service.slug] ||
    SERVICE_CATEGORY_PRICES[service.category] ||
    FALLBACK_PRICES;
  const note = SERVICE_CATEGORY_NOTES[service.category] || "single project";
  return (service.packages || []).map((p, i) => ({
    ...p,
    price: prices[i] || prices[prices.length - 1],
    priceNote: i === prices.length - 1 ? p.priceNote : note,
  }));
}

